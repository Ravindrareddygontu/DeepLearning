def get_random_pixel(keys, probabilities):
    return np.random.choice(keys, p=probabilities)


def generate_uniform_pixel():
    probabilities = [v / sum(counter.values()) for v in counter.values()]
    keys = list(counter.keys())
    return get_random_pixel(keys, probabilities)

def generate_uniform_pixels():
    random_pixels = []

    for i in range(784):
        random_pixel = generate_uniform_pixel()
        random_pixels.append(int(random_pixel))

    random_pixels = np.array(random_pixels, dtype=np.uint8).reshape(28, 28)
    image = Image.fromarray(random_pixels, 'L')

    image.save("uniform_images/image5.png")


